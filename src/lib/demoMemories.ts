export function localizeDemoMemory(mem: MemoryRecord, lang: 'en' | 'ru'): MemoryRecord {
  if (lang !== 'ru') return mem;
  const tr = DEMO_RU_TRANSLATIONS[mem.id];
  if (!tr || !mem.design) return mem;
  return {
    ...mem,
    language: 'ru',
    demoLabel: tr.demoLabel,
    title: tr.title,
    storyText: tr.storyText,
    answers: mem.answers.map((a) => ({
      ...a,
      answer: tr.answers[a.questionId] || a.answer,
    })),
    music: mem.music
      ? {
          ...mem.music,
          trackTitle: tr.trackTitle,
          artist: tr.artist,
        }
      : null,
    design: {
      ...mem.design,
      designSpec: {
        ...mem.design.designSpec,
        generatedTitle: tr.title,
        moodSummary: tr.moodSummary,
        atmosphereKeywords: tr.atmosphereKeywords,
        scrapbookPlan: mem.design.designSpec.scrapbookPlan
          ? {
              ...mem.design.designSpec.scrapbookPlan,
              backgroundMaterial: tr.backgroundMaterial,
              lightingMood: tr.lightingMood,
              ticketStubText: tr.ticketStubText || mem.design.designSpec.scrapbookPlan.ticketStubText,
              handwrittenEdgeWord:
                tr.handwrittenEdgeWord || mem.design.designSpec.scrapbookPlan.handwrittenEdgeWord,
              locationOrLabelText:
                tr.locationOrLabelText || mem.design.designSpec.scrapbookPlan.locationOrLabelText,
            }
          : undefined,
      },
    },
  };
}

