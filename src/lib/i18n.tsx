const I18nContext = createContext<I18nContextValue | null>(null);

function readInitialLanguage(): AppLanguage {
  try {
    const saved = localStorage.getItem(UI_LANG_STORAGE_KEY);
    if (saved === 'ru' || saved === 'en') return saved;
  } catch {
    // Ignore storage errors
  }
  return 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<AppLanguage>(readInitialLanguage);

  const setLang = useCallback((next: AppLanguage) => {
    setLangState(next);
    try {
      localStorage.setItem(UI_LANG_STORAGE_KEY, next);
    } catch {
      // Ignore storage errors
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const formatDate = useCallback(
    (isoDate: string, opts?: Intl.DateTimeFormatOptions) => {
      const clean = isoDate.slice(0, 10);
      const parsed = new Date(`${clean}T12:00:00`);
      if (Number.isNaN(parsed.getTime())) return isoDate;
      return parsed.toLocaleDateString(
        lang === 'ru' ? 'ru-RU' : 'en-US',
        opts || { year: 'numeric', month: 'long', day: 'numeric' }
      );
    },
    [lang]
  );

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      const dict = lang === 'ru' ? RU_DICT : EN_DICT;
      let text = dict[key] ?? EN_DICT[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
        }
      }
      return text;
    },
    [lang]
  );

  const value = useMemo<I18nContextValue>(
    () => ({
      lang,
      setLang,
      formatDate,
      months: lang === 'ru' ? MONTHS_RU : MONTHS_EN,
      weekdaysShort: lang === 'ru' ? WEEKDAYS_SHORT_RU : WEEKDAYS_SHORT_EN,
      weekdays: lang === 'ru' ? WEEKDAYS_RU : WEEKDAYS_EN,
      t,
    }),
    [lang, setLang, formatDate, t]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
